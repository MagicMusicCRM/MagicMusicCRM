// lib/core/widgets/no_open_tasks_highlight.dart
//
// Подсветка клиента, по которому не висит ни одной задачи.
//
// ✔ Требование заказчика (17.07): «в системе нашей нужно будет также отмечать
// жёлтым цветом те карточки клиентов, по которым не висит никаких задач».
//
// Смысл в том, что такой клиент — забытый: с ним никто не запланировал
// следующего шага. Красная плашка чёрного списка говорит «с этим человеком
// нельзя», жёлтая — «про этого человека забыли».
//
// Правило и цвет живут ЗДЕСЬ, а не в трёх виджетах: подсветка нужна на доске
// лидов, в списке учеников и в шапке карточки, и если каждый решит сам, они
// разъедутся — а «жёлтый» перестанет что-либо значить.

import 'package:flutter/material.dart';

import '../theme/app_theme.dart';

/// Клиент забыт: ни одной открытой задачи.
///
/// Отдельная функция, а не `== 0` по месту: сравнение с нулём одинаково
/// выглядит и для «задач нет», и для «данные ещё не пришли», а это разные вещи.
/// Здесь — именно первое, и вызывающий обязан передать уже загруженное число.
bool hasNoOpenTasks(int openTasksCount) => openTasksCount == 0;

/// Фон карточки забытого клиента. Приглушённый — подсказка, а не тревога.
Color noOpenTasksSurface(BuildContext context) =>
    Color.alphaBlend(
      AppTheme.warning.withValues(alpha: 0.10),
      Theme.of(context).colorScheme.surface,
    );

/// Рамка карточки забытого клиента.
///
/// Слабее, чем у чёрного списка (там 0.55): забытый клиент — это «займись», а
/// не «осторожно», и две подсветки не должны спорить за внимание.
BorderSide noOpenTasksBorder() =>
    BorderSide(color: AppTheme.warning.withValues(alpha: 0.45), width: 1);
