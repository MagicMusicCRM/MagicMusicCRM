// Строки взяты из настоящей выгрузки (17.07) — все девять фамилий, которые
// прогон показал как «не нашли пользователя».

import { parseStaffName } from "./staff-name";

describe("parseStaffName", () => {
  it.each([
    ["Мазалова А. Ю.", "Мазалова", ["А", "Ю"]],
    ["Богатырёва М. В.", "Богатырёва", ["М", "В"]],
    ["Крошкин Д. А.", "Крошкин", ["Д", "А"]],
    ["Сусарина А. В.", "Сусарина", ["А", "В"]],
    ["Каралкина А. А.", "Каралкина", ["А", "А"]],
    ["Назарова Н. Н.", "Назарова", ["Н", "Н"]],
  ])("%s → %s %j", (raw, lastName, initials) => {
    expect(parseStaffName(raw)).toEqual({ lastName, initials });
  });

  it("один инициал — тоже форма", () => {
    expect(parseStaffName("Мазалова А.")).toEqual({ lastName: "Мазалова", initials: ["А"] });
  });

  /**
   * «Назарова(П)» — уточнение, которым в школе различают двух однофамилиц. В
   * базе скобки нет, поэтому её выбрасываем: иначе строка не найдётся вовсе.
   * Неоднозначность («какая из Назаровых?») ловится не здесь, а на связывании —
   * оно требует единственного совпадения.
   */
  it("выбрасывает уточнение в скобках", () => {
    expect(parseStaffName("Назарова(П) Н. Н.")).toEqual({
      lastName: "Назарова",
      initials: ["Н", "Н"],
    });
  });

  it("лишние пробелы не мешают", () => {
    expect(parseStaffName("  Крошкин   Д.  А.  ")).toEqual({
      lastName: "Крошкин",
      initials: ["Д", "А"],
    });
  });

  // Не форма «фамилия + инициалы» → null, и пусть работает обычное
  // сопоставление по полному имени. Придумывать здесь нечего.
  it.each([
    ["Александра Мазалова", "полное имя, а не инициалы"],
    ["[Для всех]", "заглушка вместо человека"],
    ["", "пусто"],
    ["   ", "пробелы"],
    ["Мазалова", "одна фамилия без инициалов"],
    ["А. Ю.", "инициалы без фамилии"],
  ])("%s → null (%s)", (raw) => {
    expect(parseStaffName(raw)).toBeNull();
  });
});
