// server/src/migration/staff-name.ts
//
// Разбор имени сотрудника из выгрузки HolliHop.
//
// ЗАЧЕМ. Выгрузка пишет сотрудника как «Мазалова А. Ю.» — фамилия и инициалы. В
// нашей базе тот же человек заведён как «Александра Мазалова» (`full_name`) и
// `last_name='Мазалова'`, `first_name='Александра'`. Сопоставление по полному
// имени такое НЕ ловит никогда — ни одной из 12 692 задач.
//
// Это и есть причина, по которой `created_by` пуст у всех задач: люди в базе
// есть, а связать текст с ними было нечем. Проверено на прогоне 17.07: девять
// фамилий подряд «не нашли пользователя» — Мазалова, Богатырёва, Крошкин,
// Сусарина, Каралкина… — при том, что все они заведены менеджерами.

/** Разобранное «Фамилия И. О.». */
export interface StaffName {
  lastName: string;
  /** Инициалы по порядку: «А», «Ю». Пусто, если их в строке не было. */
  initials: string[];
}

/**
 * Разбирает «Мазалова А. Ю.» → `{ lastName: "Мазалова", initials: ["А","Ю"] }`.
 *
 * Возвращает `null`, если это не форма «фамилия + инициалы»: пусть тогда
 * работает обычное сопоставление по полному имени, а не догадка.
 *
 * Формы, которые реально встречаются в выгрузке:
 *   «Мазалова А. Ю.»      — фамилия + два инициала
 *   «Назарова Н. Н.»
 *   «Назарова(П) Н. Н.»   — уточнение в скобках, различает двух однофамилиц
 *   «Крошкин Д. А.»
 */
export function parseStaffName(raw: string): StaffName | null {
  const value = raw.trim();
  if (!value) return null;

  // «Назарова(П)» → «Назарова». Скобка уточняет человека для своих, но в базе
  // её нет; выбросить её — единственный способ вообще найти строку. Ценой
  // может быть неоднозначность (две Назаровых) — её ловит вызывающий: он
  // связывает только при единственном совпадении.
  const withoutParens = value.replace(/\([^)]*\)/g, " ").replace(/\s+/g, " ").trim();

  const match = /^([^\s.]+)\s+((?:[^\s.]\.\s*){1,3})$/u.exec(withoutParens);
  if (!match) return null;

  const lastName = match[1];
  const initials = [...match[2].matchAll(/([^\s.])\./gu)].map((m) => m[1]);
  if (!lastName || initials.length === 0) return null;
  return { lastName, initials };
}
