-- Привязка платежа к занятию + «оплаты по дням» в расписании.
--
-- ✔ Решение владельца 17.07: «должна быть привязка платежа к занятию и оплаты
-- по дням в расписании».
--
-- Чего это НЕ меняет: баланс и «Всего оплачено» как считались по всем платежам
-- ученика, так и считаются. Ссылка — это пометка «этот приход за вот это
-- занятие», а не отдельный кошелёк. Иначе платёж без ссылки (а такими будут
-- все 100% существующих) выпал бы из расчётов, и балансы поехали бы у всех.
--
-- ⚠️ В API HolliHop такой связи нет: `GetPayments` отдаёт платёж клиента с
-- датой и суммой, но без занятия (разведка 16.07, docs/import/
-- hollihop_api_probe_2026-07-16.md). Импортированные платежи останутся без
-- ссылки — заполнять её задним числом неоткуда.

alter table app.payments
  add column if not exists lesson_id uuid
    references app.lessons(id) on delete set null;

-- Занятие → его платежи: этим запросом лента дат в карточке красит день
-- «оплачен».
create index if not exists payments_lesson_idx
  on app.payments (lesson_id)
  where lesson_id is not null and deleted_at is null;

comment on column app.payments.lesson_id is
  'Занятие, за которое пришёл платёж. NULL — платёж не разнесён по занятиям (норма: так выглядят все импортированные и любое пополнение счёта авансом).';
