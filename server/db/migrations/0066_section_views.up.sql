-- Счётчики непросмотренного по разделам: «когда пользователь смотрел раздел».
--
-- ✔ Требование заказчика 17.07: «по приложению в зависимости от изменений в
-- определённых папках или окнах должны приходить свои уведомления с счётчиком
-- непрочитанных или непросмотренных изменений».
-- ✔ Решение заказчика: хранить НА СЕРВЕРЕ, а не в памяти приложения — счётчик
-- обязан пережить перезапуск и совпадать на телефоне и на компьютере.
--
-- Модель: не «счётчик», а ОТМЕТКА ВРЕМЕНИ. Хранить число непросмотренного
-- пришлось бы инкрементить из каждого места, где что-то создаётся, — и любое
-- пропущенное место тихо ломало бы счёт навсегда. Отметка «когда я последний
-- раз открывал раздел» самодостаточна: число всегда считается запросом от неё,
-- и новый вид изменений начинает учитываться сам, без правки записи.
--
-- Раздел — строка, а не enum: набор вкладок меняется чаще, чем стоит трогать
-- схему (enum в Postgres нельзя пополнить в той же транзакции, где его
-- используют). Мусора не будет: пишет только сервер, из своего списка.
create table if not exists app.section_views (
  user_id uuid not null references app.users(id) on delete cascade,
  section text not null,
  last_seen_at timestamptz not null default now(),
  primary key (user_id, section)
);

comment on table app.section_views is
  'Когда пользователь последний раз открывал раздел CRM. Из этой отметки считается счётчик «непросмотренных изменений» на вкладке.';
comment on column app.section_views.section is
  'Ключ раздела: clients | tasks | schedule | finance. Совпадает с sectionKey в lib/core/services/alert_policy.dart.';
comment on column app.section_views.last_seen_at is
  'Всё, что появилось ПОЗЖЕ этого момента, считается непросмотренным. Новому пользователю строки нет — счёт идёт от его created_at, а не от начала времён.';

-- ⚠️ Отсечка для тех, кто уже есть. Без неё счётчики врут в первый же день.
--
-- Отсчёт по умолчанию — от `users.created_at`. Для нового сотрудника это верно:
-- он появился позже данных, и «новое с его прихода» осмысленно. Но у всех, кто
-- заведён ДО пересборки базы 17.07, всё наоборот: `created_at` у 33 725
-- занятий — это момент импорта, то есть позже их регистрации. Проверено на
-- живой базе: у управляющего вкладка «Расписание» показала бы 33 725 — всю
-- базу. Цифра такого размера не «зовёт посмотреть», она приучает не смотреть.
--
-- Поэтому: всё, что было до этой миграции, считается просмотренным. Счёт
-- начинается с чистого листа — с того, что появится дальше.
insert into app.section_views (user_id, section, last_seen_at)
select u.id, s.section, now()
from app.users u
cross join (values ('clients'), ('tasks'), ('schedule'), ('finance')) as s(section)
where u.deleted_at is null
on conflict (user_id, section) do nothing;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'magiccrm_app') then
    grant select, insert, update, delete on app.section_views to magiccrm_app;
  end if;
end $$;
